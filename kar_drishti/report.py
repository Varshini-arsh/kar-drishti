"""One-click case analysis report (self-contained HTML; print to PDF from the browser)."""
from __future__ import annotations

import html
from datetime import datetime

import pandas as pd

import branding

from . import risk
from .data import Case
from .money_trail import inr

CSS = """
body{font-family:Segoe UI,Arial,sans-serif;margin:32px;color:#222;max-width:1100px}
h1{font-size:24px;margin-bottom:0} h2{font-size:18px;border-bottom:2px solid #0F766E;padding-bottom:4px;margin-top:32px}
h3{font-size:15px;margin:18px 0 6px} .muted{color:#666;font-size:12px}
table{border-collapse:collapse;width:100%;font-size:12px;margin:6px 0 14px}
th,td{border:1px solid #ddd;padding:5px 7px;text-align:left;vertical-align:top} th{background:#F0FDFA}
.HIGH{color:#fff;background:#d62728;padding:1px 6px;border-radius:3px}
.MEDIUM{color:#fff;background:#f58518;padding:1px 6px;border-radius:3px}
.LOW{background:#ddd;padding:1px 6px;border-radius:3px}
.box{background:#fff8e1;border:1px solid #f0c36d;padding:10px 14px;margin:14px 0;font-size:13px}
.kpi{display:inline-block;margin:0 22px 8px 0}.kpi b{display:block;font-size:20px}
.draft{border:2px dashed #DC2626;color:#DC2626;font-weight:700;padding:6px 12px;margin-bottom:14px;letter-spacing:.04em}
.sig{white-space:pre-line;margin-top:36px;border-top:1px solid #ddd;padding-top:12px;font-size:13px}
@media print{body{margin:10mm}.pb{page-break-before:always}}
"""


def _t(df: pd.DataFrame) -> str:
    return df.to_html(index=False, escape=True, border=0)


def build_report(case: Case, analysis: risk.Analysis, holder_ids: list[str] | None = None,
                 officer_notes: str = "", executive_summary: str = "", max_holders: int = 15,
                 signature: str = "") -> str:
    """Self-contained HTML report. Always marked DRAFT; `signature` is the officer's signature block."""
    r = analysis.risk
    sel = r[r.holder_id.isin(holder_ids)] if holder_ids else r[r.risk_level != "LOW"].head(max_holders)
    s = case.summary()
    tx = case.transactions
    app = html.escape(branding.APP_NAME)
    parts = [f"<html><head><meta charset='utf-8'><title>DRAFT - {app} case analysis report</title>"
             f"<style>{CSS}</style></head><body>",
             f"<div class='draft'>{html.escape(branding.DRAFT_MARK)}</div>",
             "<h1>Case Analysis Report (DRAFT)</h1>",
             f"<div class='muted'>Case: {html.escape(case.name)} | Generated {datetime.now():%d %b %Y %H:%M} | "
             f"Prepared offline with {app} (decision-support tool)</div>",
             "<div class='box'><b>Note:</b> This report is generated by an analytical tool to assist the officer. "
             "All findings are indicative and must be verified by the officer against source records before "
             "any action. The tool does not decide any case.</div>",
             "<h2>1. Case overview</h2>",
             f"<div class='kpi'>Persons<b>{s['persons']}</b></div><div class='kpi'>Firms<b>{s['firms']}</b></div>"
             f"<div class='kpi'>Bank accounts<b>{s['accounts']}</b></div>"
             f"<div class='kpi'>Transactions<b>{s['transactions']:,}</b></div>"
             f"<div class='kpi'>Total credits<b>{inr(s['total_credits'])}</b></div>"
             f"<div class='kpi'>Period<b>{s['date_from']:%d-%m-%Y} to {s['date_to']:%d-%m-%Y}</b></div>",
             f"<p>{(r.risk_level == 'HIGH').sum()} holders are HIGH risk and {(r.risk_level == 'MEDIUM').sum()} are "
             f"MEDIUM risk. Patterns detected: " +
             ", ".join(f"{risk.PATTERN_LABEL.get(p, p)} ({n})" for p, n in analysis.findings.pattern.value_counts().items())
             + ".</p>"]
    if executive_summary:
        parts.append(f"<h3>Summary</h3><p>{html.escape(executive_summary).replace(chr(10), '<br>')}</p>")
    if officer_notes:
        parts.append(f"<h3>Officer's notes</h3><p>{html.escape(officer_notes).replace(chr(10), '<br>')}</p>")

    q = sel.copy()
    q["risk_level"] = q.risk_level.map(lambda l: f"<span class='{l}'>{l}</span>")
    q["patterns"] = q["flags"].map(lambda f: ", ".join(risk.PATTERN_LABEL.get(x, x) for x in f))
    q["total_credits"] = q.total_credits.map(inr)
    q["declared_income"] = [inr(v) if f else "Not filed" for v, f in zip(sel.declared_income, sel.filed)]
    parts += ["<h2>2. Priority list</h2>",
              q[["holder_id", "name", "holder_type", "risk_score", "risk_level", "patterns", "total_credits",
                 "declared_income"]].to_html(index=False, escape=False, border=0)]

    parts.append("<h2 class='pb'>3. Findings and evidence</h2>")
    for row in sel.itertuples(index=False):
        f = analysis.findings[analysis.findings.holder_id == row.holder_id]
        parts.append(f"<h3>{html.escape(row.name)} ({row.holder_id}) - score {row.risk_score:.0f} "
                     f"<span class='{row.risk_level}'>{row.risk_level}</span></h3><ul>")
        for fr in f.itertuples(index=False):
            parts.append(f"<li><b>{risk.PATTERN_LABEL.get(fr.pattern, fr.pattern)}:</b> {html.escape(fr.summary)}</li>")
        parts.append("</ul>")
        if row.breakdown:
            parts.append(f"<div class='muted'>How the score was built: {html.escape(risk.score_text(row._asdict()))}."
                         + (" ML hint: unusual behaviour compared with other holders (not counted in the score)."
                            if row.outlier else "") + "</div>")
        ev = [t for e in f.evidence for t in e]
        if ev and case.gst_invoices is not None and len(case.gst_invoices):
            gi = case.gst_invoices[case.gst_invoices.invoice_id.isin(ev)]
            if len(gi):
                gi = gi.sort_values("taxable_value", ascending=False).head(10)
                gi = gi.assign(invoice_date=gi.invoice_date.dt.strftime("%d-%m-%Y"),
                               taxable_value=gi.taxable_value.map(lambda v: f"{v:,.0f}"),
                               eway_bill_no=gi.eway_bill_no.fillna("NONE"))
                parts.append("<div class='muted'>Key GST invoices (top 10 by value)</div>" +
                             _t(gi[["invoice_id", "invoice_date", "seller_firm_id", "buyer_firm_id", "hsn",
                                    "taxable_value", "eway_bill_no"]]))
        if ev:
            e = tx[tx.txn_id.isin(ev)].sort_values("amount", ascending=False).head(10)
            e = e.assign(txn_date=e.txn_date.dt.strftime("%d-%m-%Y"), amount=e.amount.map(lambda v: f"{v:,.0f}"))
            parts.append("<div class='muted'>Key evidence transactions (top 10 by amount)</div>" +
                         _t(e[["txn_id", "txn_date", "account_id", "mode", "direction", "amount",
                               "counterparty_name", "narration"]]))

    if analysis.chains:
        parts.append("<h2>4. Circular money flows (round-tripping)</h2>")
        rows = [{"route": " → ".join(case.holder_name(h) for h in c["path"]),
                 "start": c["start_date"].strftime("%d-%m-%Y"), "days": c["days"],
                 "amount out": inr(c["amount_out"]), "amount back": inr(c["amount_back"]),
                 "transactions": ", ".join(c["txn_ids"])} for c in analysis.chains]
        parts.append(_t(pd.DataFrame(rows)))
    sus = [c for c in analysis.clusters if c["suspicious"]]
    if sus:
        parts.append("<h2>5. Linked groups (possible shell networks)</h2>")
        for c in sus:
            parts.append(f"<p><b>{c['cluster_id']}</b>: {len(c['members'])} entities - " +
                         ", ".join(html.escape(f"{case.holder_name(m)} ({m})") for m in c["members"]) +
                         f". Shared links: {c['shared_links']}. Money moved inside group: {inr(c['internal_flow'])}.</p>")
    if analysis.gst_cycles:
        parts.append("<h2>6. GST circular trading loops</h2>")
        parts.append(_t(pd.DataFrame([{
            "route": " → ".join(case.holder_name(x) for x in c["route"]), "invoices": c["invoices"],
            "value round the loop": inr(c["total_value"]), "ITC generated": inr(c["itc_generated"]),
            "without e-way bill": f"{c['no_eway_share']:.0%}"} for c in analysis.gst_cycles])))
    parts.append("<h2>7. Method</h2><p class='muted'>Rule-based detectors (cash structuring below the ₹50,000 "
                 "PAN-quoting limit, pass-through accounts, temporal cycle search for round-tripping, credits vs "
                 "declared income/turnover, large round-figure cash, GST invoice loops, ITC set-off without cash payment, "
                 "missing e-way bills, ITC from flagged suppliers; GST checks only when the add-on is on) and "
                 "graph analysis of shared phone/address/director links. Risk score = sum of (weight x strength) for each red flag, "
                 "capped at 100; an Isolation Forest model is shown only as a hint and adds no points. All processing ran locally; no data left "
                 "this computer.</p>")
    if signature:
        parts.append(f"<div class='sig'>{html.escape(signature)}</div>")
    parts.append("</body></html>")
    return "\n".join(parts)
